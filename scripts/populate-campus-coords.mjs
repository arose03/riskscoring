function main() {
  const db = new Database(DB_PATH);

  const universities = db
    .prepare('SELECT id, name FROM universities WHERE campus_lat IS NULL OR campus_lng IS NULL')
    .all();

  console.log(`Found ${universities.length} universities to update`);

  const update = db.prepare('UPDATE universities SET campus_lat = ?, campus_lng = ? WHERE id = ?');

  let success = 0;
  let missing = 0;
  const missingNames = [];

  for (const uni of universities) {
    const coords = CAMPUS_COORDS[uni.name];
    if (coords) {
      update.run(coords[0], coords[1], uni.id);
      success++;
    } else {
      missing++;
      missingNames.push(uni.name);
    }
  }

  console.log(`Updated ${success} universities`);
  if (missing > 0) {
    console.log(`Missing coordinates for ${missing}:`, missingNames.join(', '));
  }

  // Verify
  const nullCount = db.prepare('SELECT COUNT(*) as c FROM universities WHERE campus_lat IS NULL').get();
  console.log(`Remaining without coordinates: ${nullCount.c}`);

  db.close();
}

main();
